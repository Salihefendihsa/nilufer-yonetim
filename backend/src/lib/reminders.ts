/** 07:00 daily digest email for OWNER(s) with dailyDigestEnabled. */
export async function sendDailyDigest(): Promise<number> {
  const owners = await getOwners();
  const eligibleOwners: UserForEmail[] = [];
  for (const owner of owners) {
    if (await shouldEmail(owner.id, "dailyDigestEnabled")) {
      eligibleOwners.push(owner);
    }
  }
  if (eligibleOwners.length === 0) return 0;

  const now = new Date();
  const startOfDay = new Date(now);
  startOfDay.setHours(0, 0, 0, 0);
  const endOfDay = new Date(now);
  endOfDay.setHours(23, 59, 59, 999);
  const cutoff = new Date();
  cutoff.setHours(cutoff.getHours() - PENDING_APPROVAL_HOURS);

  const [todaysJobsCount, newQuotesCount, pendingAdvances, pendingQuotes, products] = await Promise.all([
    prisma.job.count({ where: { scheduledAt: { gte: startOfDay, lte: endOfDay } } }),
    prisma.quoteRequest.count({ where: { status: "NEW" } }),
    prisma.advanceRequest.count({ where: { status: AdvanceStatus.PENDING } }),
    prisma.quoteRequest.count({ where: { status: "NEW", createdAt: { lte: cutoff } } }),
    prisma.product.findMany(),
  ]);

  const criticalProducts = products.filter((p) => Number(p.currentStock) <= Number(p.criticalThreshold));

  const dateLabel = now.toLocaleDateString("tr-TR", { day: "numeric", month: "long", year: "numeric" });

  const html = `
    <div style="font-family: Arial, sans-serif; max-width: 560px;">
      <h2 style="color: #1F5C3D;">Nilüfer İlaçlama - Bugünün Özeti</h2>
      <p style="color: #555;">${dateLabel}</p>
      <table style="width: 100%; border-collapse: collapse; margin-top: 16px;">
        <tr><td style="padding: 8px 0; border-bottom: 1px solid #eee;">Bugünkü iş sayısı</td><td style="padding: 8px 0; border-bottom: 1px solid #eee; text-align: right; font-weight: bold;">${todaysJobsCount}</td></tr>
        <tr><td style="padding: 8px 0; border-bottom: 1px solid #eee;">Yeni teklif talebi</td><td style="padding: 8px 0; border-bottom: 1px solid #eee; text-align: right; font-weight: bold;">${newQuotesCount}</td></tr>
        <tr><td style="padding: 8px 0; border-bottom: 1px solid #eee;">Bekleyen avans talebi</td><td style="padding: 8px 0; border-bottom: 1px solid #eee; text-align: right; font-weight: bold;">${pendingAdvances}</td></tr>
        <tr><td style="padding: 8px 0; border-bottom: 1px solid #eee;">48 saatten eski bekleyen teklif</td><td style="padding: 8px 0; border-bottom: 1px solid #eee; text-align: right; font-weight: bold;">${pendingQuotes}</td></tr>
      </table>
      ${
        criticalProducts.length > 0
          ? `<h3 style="color: #B3261E; margin-top: 20px;">Kritik stok uyarıları</h3>
             <ul>${criticalProducts.map((p) => `<li>${p.name} — ${Number(p.currentStock)} ${p.unit}</li>`).join("")}</ul>`
          : `<p style="margin-top: 20px; color: #1F5C3D;">Kritik stok uyarısı yok.</p>`
      }
    </div>
  `;

  for (const owner of eligibleOwners) {
    await sendEmail(owner.email, `Bugünün Özeti - ${dateLabel}`, html);
  }

  return eligibleOwners.length;
}

const RENEWAL_ALERT_WINDOW_DAYS = 7;

/**
 * Bölüm B (2. tur): mevcut `sendContractExpiryReminders` 30 günlük genel bir
 * bilgilendirme özeti (toplam sayı, günde bir kez 08:00'de zaten çalışıyor).
 * Bu fonksiyon AYRI ve daha aciliyetli — bitişine 7 gün veya daha az kalan
 * HER sözleşme için ayrı ayrı, sözleşme bazlı `lastRenewalAlertAt` ile
 * günlük dedup'lı bir hatırlatma gönderir. İkisi birbirinin yerini almaz,
 * tamamlayıcıdır (30 gün = "haberin olsun", 7 gün = "acele et").
 */
/** 7 günlük yenileme penceresi — sweep ve yönetici özeti aynı filtreyi paylaşır. */
export function contractRenewalWindowWhere(now = new Date()) {
  const windowEnd = new Date(now);
  windowEnd.setDate(windowEnd.getDate() + RENEWAL_ALERT_WINDOW_DAYS);
  return { status: "ACTIVE", endDate: { gte: now, lte: windowEnd } };
}

export async function sweepContractRenewalAlerts(): Promise<number> {
  const now = new Date();

  const contracts = await prisma.contract.findMany({
    where: contractRenewalWindowWhere(now),
    include: { customer: { select: { fullName: true } } },
  });

  let notifiedCount = 0;
  for (const contract of contracts) {
    if (contract.lastRenewalAlertAt && isSameCalendarDay(contract.lastRenewalAlertAt, now)) continue;

    const daysLeft = Math.max(0, Math.ceil((contract.endDate.getTime() - now.getTime()) / (1000 * 60 * 60 * 24)));
    await notifyManagement(
      "Sözleşme yenileme hatırlatması",
      `${contract.customer.fullName} sözleşmesi ${daysLeft} gün içinde sona eriyor.`,
      { type: "contract_renewal", relatedType: "Contract", relatedId: contract.id }
    );
    await prisma.contract.update({ where: { id: contract.id }, data: { lastRenewalAlertAt: now } });
    notifiedCount++;
  }

  return notifiedCount;
}

/**
 * Bölüm AM (9. tur): SKT'si 7 gün içinde dolacak veya dolmuş, bakiyesi > 0
 * partiler için yönetime (OWNER/MANAGER) günlük dedup'lı bildirim —
 * `ProductBatch.lastExpiryAlertAt` ile aynı takvim günü kontrolü
 * (lastLowStockAlertAt deseni). Bakiyesi sıfırlanan parti listeden düşer.
 * @param onlyProductIds Testler/manuel tetikleme için kapsam daraltıcı —
 *   üretimde verilmez (bkz. lib/cron.ts).
 */
export async function sweepExpiringBatchAlerts(onlyProductIds?: string[]): Promise<number> {
  const now = new Date();
  const batches = await findExpiringBatches(EXPIRY_ALERT_WINDOW_DAYS, onlyProductIds);

  let notifiedCount = 0;
  for (const batch of batches) {
    if (batch.lastExpiryAlertAt && isSameCalendarDay(batch.lastExpiryAlertAt, now)) continue;

    const body = batch.isExpired
      ? `${batch.product.name} · Parti ${batch.batchNumber} son kullanma tarihi GEÇTİ (${Number(batch.quantityRemaining)} ${batch.product.unit} kaldı). İmha/iade edilmeli.`
      : `${batch.product.name} · Parti ${batch.batchNumber} ${batch.daysLeft} gün içinde son kullanma tarihine ulaşıyor (${Number(batch.quantityRemaining)} ${batch.product.unit} kaldı).`;

    await notifyManagement(
      batch.isExpired ? "Süresi dolmuş kimyasal partisi" : "Son kullanma tarihi yaklaşan parti",
      body,
      { type: "batch_expiry", relatedType: "Product", relatedId: batch.productId }
    );
    await prisma.productBatch.update({ where: { id: batch.id }, data: { lastExpiryAlertAt: now } });
    notifiedCount++;
  }

  return notifiedCount;
}
